/**
 * Traces the drawn حصالة wordmark into a vector outline.
 *
 *   node scripts/make-wordmark.mjs
 *
 * The source is a brush drawing in `hasaleh media/hasaleh logo.png`, which lives
 * outside this repo alongside the scan. A bitmap could not be used directly: the
 * wordmark sits in the masthead at ~28px and must take its colour from `--mark` like
 * everything else on the page, and neither is possible with a flat PNG. So the black
 * pixels are traced to a path and emitted as `public/wordmark.svg`, which the masthead
 * uses as a CSS mask over `currentColor` — the colour then comes from the cascade, not
 * from the asset.
 *
 * The tracing itself lives in scripts/lib/trace-bitmap.mjs, shared with the favicon.
 *
 * Idempotent. Re-run if the drawing is redrawn.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { traceBitmap, loopsToPath } from './lib/trace-bitmap.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SOURCE = path.resolve(ROOT, '..', 'hasaleh media', 'hasaleh logo.png');
const OUTPUT = path.join(ROOT, 'public', 'wordmark.svg');

/** Width the outline is normalised to. Height follows from the drawing's aspect. */
const VIEW_WIDTH = 1000;
/**
 * Tolerance in viewBox units. The wordmark is displayed around a fifth of this
 * normalised width, so 1.1 units is well under a rendered pixel — but it removes the
 * long straight runs the pixel walk generates, which is most of the path data.
 */
const TOLERANCE = 1.1;

const traced = await traceBitmap(SOURCE, { minLoopArea: 24 });
const outline = loopsToPath(traced.loops, traced.bbox, {
  targetWidth: VIEW_WIDTH,
  tolerance: TOLERANCE,
  precision: 1,
});

// Rounded, because a fractional viewBox height would put the mask on a half-pixel.
const viewHeight = Math.round(outline.height);

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW_WIDTH} ${viewHeight}">
  <!-- Generated by scripts/make-wordmark.mjs from "hasaleh media/hasaleh logo.png".
       The outline is the drawing's own pixel boundary, simplified. Do not hand-edit.

       No colour is stated here on purpose: the masthead uses this file as a CSS
       mask over currentColor, so the wordmark inherits the ink token along with the
       rest of the page and cannot drift from it. (A double hyphen is illegal inside
       an XML comment, which is why the token is not named here.) -->
  <title>حصالة</title>
  <path fill="#000" fill-rule="evenodd" d="${outline.d}"/>
</svg>
`;

fs.writeFileSync(OUTPUT, svg);
const { minX, minY, maxX, maxY } = traced.bbox;
console.log(
  `source ${traced.width}×${traced.height}, ` +
    `ink bbox ${maxX - minX + 1}×${maxY - minY + 1} at (${minX},${minY})`,
);
console.log(`loops ${traced.loops.length}, ${traced.tracedPoints} points -> ${outline.points}`);
console.log(
  `wrote public/wordmark.svg  ${svg.length} bytes  viewBox 0 0 ${VIEW_WIDTH} ${viewHeight}`,
);
